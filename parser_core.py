# -*- coding: utf-8 -*-
"""
Модуль синтаксического анализатора для функции print() в Python.
Содержит логику анализа и справочные тексты для меню "Текст" и "Справка".
"""

class PrintParser:
    @staticmethod
    def analyze(text, file_path="<текущий документ>"):
        """
        Анализирует текст программы на наличие ошибок в вызовах print(...).
        Возвращает список ошибок: [{'file': str, 'line': int, 'column': int, 'message': str}]
        """
        errors = []
        lines = text.splitlines()
        
        for line_idx, line in enumerate(lines, start=1):
            stripped = line.strip()
            if not stripped or stripped.startswith('#'):
                continue
                
            # Проверка вызовов print
            if 'print' in stripped:
                open_count = line.count('(')
                close_count = line.count(')')
                
                if open_count > close_count:
                    col = line.rfind('(') + 1
                    errors.append({
                        'file': file_path,
                        'line': line_idx,
                        'column': col,
                        'message': 'Незакрытая круглая скобка в вызове print'
                    })
                elif close_count > open_count:
                    col = line.rfind(')') + 1
                    errors.append({
                        'file': file_path,
                        'line': line_idx,
                        'column': col,
                        'message': 'Лишняя закрывающая скобка'
                    })
                
                # Проверка строковых литералов внутри print(...)
                if '(' in line and ')' in line:
                    inside = line[line.find('(')+1:line.rfind(')')]
                    single_q = inside.count("'")
                    double_q = inside.count('"')
                    if single_q % 2 != 0 or double_q % 2 != 0:
                        col = line.find("'") if single_q % 2 != 0 else line.find('"')
                        if col == -1: 
                            col = 1
                        else: 
                            col += 1
                        errors.append({
                            'file': file_path,
                            'line': line_idx,
                            'column': col,
                            'message': 'Незакрытая текстовая константа (строка) в аргументах print'
                        })
            else:
                # Общая проверка скобок для других строк (например, присваиваний)
                oc = line.count('(') - line.count(')')
                if oc > 0:
                    errors.append({
                        'file': file_path,
                        'line': line_idx,
                        'column': line.rfind('(') + 1,
                        'message': 'Незакрытая круглая скобка'
                    })

        return errors


